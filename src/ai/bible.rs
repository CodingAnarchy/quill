//! The on-disk story-bible format, shared by the AI trackers (characters #74,
//! timeline #75, setting #77). A bible file is YAML front matter, a delimited
//! **generated block** (rewritten each pass, change-detected by a `digest`), and
//! an author-owned **Notes block** carried over verbatim. This module is
//! content-agnostic: each tracker builds its own front matter + generated body
//! and calls [`render`].

use std::collections::hash_map::DefaultHasher;
use std::hash::{Hash, Hasher};
use std::path::Path;

const GEN_START: &str = "<!-- generated:start -->";
const GEN_END: &str = "<!-- generated:end -->";
const NOTES_START: &str = "<!-- notes:start -->";
const NOTES_END: &str = "<!-- notes:end -->";
const NOTES_PLACEHOLDER: &str = "## Notes\n\n_Your notes here — preserved across regeneration._\n";

/// Assemble a bible file from caller-built `front` matter lines (each ending in
/// `\n`, no trailing `---`), the regenerated `generated` body, the author's
/// `notes`, and the generation date `today`. Adds the `generated`/`digest` front
/// matter and the block markers.
pub fn render(front: &str, generated: &str, notes: &str, today: &str) -> String {
    let digest = digest(generated);
    format!(
        "---\n# Generated by Quill — edit the Notes section; the rest is rewritten \
on the next pass.\n{front}generated: {today}\ndigest: {digest}\n---\n\n\
{GEN_START}\n{generated}{GEN_END}\n\n{NOTES_START}\n{notes}{NOTES_END}\n"
    )
}

/// Append a `## {heading}` section with one `- ` bullet per item and a trailing
/// blank line, or nothing when `items` is empty — the shared shape for the
/// bullet-list sections in generated bible / notes blocks.
pub(crate) fn bullet_section(body: &mut String, heading: &str, items: &[String]) {
    if items.is_empty() {
        return;
    }
    body.push_str(&format!("## {heading}\n"));
    for item in items {
        body.push_str(&format!("- {item}\n"));
    }
    body.push('\n');
}

/// The author's Notes block from an existing file, or the placeholder so a fresh
/// file still has the section.
pub fn extract_notes(existing: &str) -> String {
    between(existing, NOTES_START, NOTES_END).unwrap_or_else(|| NOTES_PLACEHOLDER.to_string())
}

/// Whether `existing`'s generated block has been hand-edited since it was written
/// (its content no longer matches the `digest:` recorded in the front matter).
pub fn is_hand_edited(existing: &str) -> bool {
    let Some(stored) = front_field(existing, "digest") else {
        return false; // no digest (older/foreign file) — treat as clean
    };
    let current = between(existing, GEN_START, GEN_END).unwrap_or_default();
    digest(&current) != stored
}

/// A filename-safe slug, e.g. "Mara Vance" → "mara-vance" (→ "unnamed" if empty).
pub fn slug(name: &str) -> String {
    let mut out = String::new();
    let mut prev_dash = false;
    for ch in name.chars() {
        if ch.is_alphanumeric() {
            out.extend(ch.to_lowercase());
            prev_dash = false;
        } else if !prev_dash && !out.is_empty() {
            out.push('-');
            prev_dash = true;
        }
    }
    let slug = out.trim_end_matches('-').to_string();
    if slug.is_empty() {
        "unnamed".to_string()
    } else {
        slug
    }
}

/// Minimal YAML scalar quoting: quote when the value could be misread (including
/// flow-context chars `[]{},` since aliases are written as `[a, b]`).
pub fn yaml(value: &str) -> String {
    let needs_quote = value.is_empty()
        || value.starts_with(|c: char| c.is_whitespace())
        || value.ends_with(|c: char| c.is_whitespace())
        || value.contains([':', '#', '"', '\'', '[', ']', '{', '}', ',']);
    if needs_quote {
        format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
    } else {
        value.to_string()
    }
}

/// Stable change-detection hash of a block of text (not cryptographic). The one
/// source of the persisted-hash format, shared by the generated-block digest and
/// the incremental-scoping chapter digests (#90).
pub(crate) fn digest(generated: &str) -> String {
    let mut h = DefaultHasher::new();
    generated.hash(&mut h);
    format!("{:016x}", h.finish())
}

/// An existing single-file bible (`bible/<rel>`) as raw text — the cache for an
/// incremental revise (#90), empty when absent.
pub(crate) fn raw_file(root: &Path, rel: &str) -> String {
    std::fs::read_to_string(root.join("bible").join(rel)).unwrap_or_default()
}

/// The existing `.md` bible files under `bible/<dir>/` (e.g. the per-character
/// profiles), concatenated as the cache for an incremental revise (#90).
pub(crate) fn raw_dir(root: &Path, dir: &str) -> String {
    let mut out = String::new();
    let Ok(entries) = std::fs::read_dir(root.join("bible").join(dir)) else {
        return out;
    };
    let mut files: Vec<std::path::PathBuf> = entries.flatten().map(|e| e.path()).collect();
    files.sort();
    for path in files {
        if path.extension().and_then(|e| e.to_str()) == Some("md") {
            if let Ok(text) = std::fs::read_to_string(&path) {
                out.push_str(&text);
                out.push_str("\n\n");
            }
        }
    }
    out
}

/// The text strictly between `start` and `end` markers, if both are present.
fn between(text: &str, start: &str, end: &str) -> Option<String> {
    let s = text.find(start)? + start.len();
    let e = text[s..].find(end)? + s;
    Some(text[s..e].trim_start_matches('\n').to_string())
}

/// A scalar field value from the YAML front matter (first `key: value` line).
pub fn front_field(text: &str, key: &str) -> Option<String> {
    let body = text.strip_prefix("---\n")?;
    let end = body.find("\n---")?;
    body[..end].lines().find_map(|line| {
        let (k, v) = line.split_once(':')?;
        (k.trim() == key).then(|| v.trim().to_string())
    })
}

/// The `- item` bullets under the `## {heading}` section of a bible file, up to
/// the next `##` heading or block marker. The reader counterpart to the section
/// writing the trackers do (e.g. the setting "Gazetteer" list).
pub fn list_items(text: &str, heading: &str) -> Vec<String> {
    let mut items = Vec::new();
    let mut in_section = false;
    for line in text.lines() {
        if let Some(h) = line.strip_prefix("## ") {
            in_section = h.trim() == heading;
        } else if in_section {
            if line.starts_with("<!--") {
                break; // end of the generated block
            }
            if let Some(item) = line.strip_prefix("- ") {
                items.push(item.trim().to_string());
            }
        }
    }
    items
}

// --- Reading the project's bible (the typed counterpart to the writers) -----

/// The place/term gazetteer from `bible/setting.md` (empty when absent).
pub fn gazetteer(root: &Path) -> Vec<String> {
    let path = root.join("bible").join("setting.md");
    std::fs::read_to_string(path)
        .map(|t| list_items(&t, "Gazetteer"))
        .unwrap_or_default()
}

/// The character names from `bible/characters/*.md` front matter (empty when
/// absent), sorted for a deterministic order. De-duplication is the caller's job
/// (e.g. `known_entities` dedups the combined gazetteer + names).
pub fn character_names(root: &Path) -> Vec<String> {
    let dir = root.join("bible").join("characters");
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|entry| std::fs::read_to_string(entry.path()).ok())
        .filter_map(|text| front_field(&text, "name"))
        .collect();
    names.sort();
    names
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn list_items_reads_a_section_and_stops_at_the_next() {
        let text = "## Gazetteer\n- Aldermoor\n- lightsteel\n\n## Other\n- nope\n";
        assert_eq!(
            list_items(text, "Gazetteer"),
            vec!["Aldermoor", "lightsteel"]
        );
        assert_eq!(list_items(text, "Other"), vec!["nope"]);
        assert!(list_items(text, "Missing").is_empty());
    }

    #[test]
    fn list_items_stops_at_the_generated_block_marker() {
        let text = "## Gazetteer\n- Aldermoor\n<!-- generated:end -->\n- not-this\n";
        assert_eq!(list_items(text, "Gazetteer"), vec!["Aldermoor"]);
    }

    #[test]
    fn front_field_reads_a_front_matter_scalar() {
        let text = "---\nname: Mara Vance\nrole: protagonist\n---\nbody\n";
        assert_eq!(front_field(text, "name").as_deref(), Some("Mara Vance"));
        assert_eq!(front_field(text, "missing"), None);
    }

    #[test]
    fn gazetteer_and_character_names_read_the_bible_dir() {
        let mut root = std::env::temp_dir();
        root.push(format!("quill-bible-read-{}", std::process::id()));
        let chars = root.join("bible").join("characters");
        std::fs::create_dir_all(&chars).unwrap();
        // A setting file rendered the same way the writer does.
        let setting = render(
            "title: Setting\n",
            "## Gazetteer\n- Aldermoor\n- lightsteel\n",
            "## Notes\n",
            "2026-06-19",
        );
        std::fs::write(root.join("bible").join("setting.md"), setting).unwrap();
        std::fs::write(chars.join("mara.md"), "---\nname: Mara Vance\n---\n").unwrap();

        assert_eq!(gazetteer(&root), vec!["Aldermoor", "lightsteel"]);
        assert_eq!(character_names(&root), vec!["Mara Vance"]);
        std::fs::remove_dir_all(&root).ok();
    }

    #[test]
    fn readers_are_empty_when_the_bible_is_absent() {
        let root = std::path::Path::new("/nonexistent-quill-bible");
        assert!(gazetteer(root).is_empty());
        assert!(character_names(root).is_empty());
    }

    #[test]
    fn slug_is_filename_safe() {
        assert_eq!(slug("Mara Vance"), "mara-vance");
        assert_eq!(slug("Dr. O'Brien"), "dr-o-brien");
        assert_eq!(slug("  "), "unnamed");
    }

    #[test]
    fn yaml_quotes_only_when_needed() {
        assert_eq!(yaml("Mara"), "Mara");
        assert_eq!(yaml("Mara, Ms. Vance"), "\"Mara, Ms. Vance\""); // comma → flow-unsafe
        assert_eq!(yaml("a: b"), "\"a: b\"");
    }

    #[test]
    fn render_preserves_notes_and_round_trips() {
        let notes = "## Notes\n\nKeep me.\n";
        let file = render(
            "name: Mara\n",
            "## Physical\n- green eyes\n",
            notes,
            "2026-06-19",
        );
        assert!(file.contains("name: Mara"));
        assert!(file.contains("green eyes"));
        assert_eq!(extract_notes(&file).trim(), notes.trim());
        assert!(!is_hand_edited(&file), "freshly rendered file is clean");
    }

    #[test]
    fn edited_generated_block_is_detected_not_notes() {
        let file = render(
            "name: Mara\n",
            "## Physical\n- green eyes\n",
            NOTES_PLACEHOLDER,
            "2026-06-19",
        );
        assert!(is_hand_edited(&file.replace("green eyes", "blue eyes")));
        assert!(!is_hand_edited(
            &file.replace("preserved across regeneration", "MY EDIT")
        ));
    }

    #[test]
    fn extract_notes_falls_back_to_placeholder() {
        assert!(extract_notes("no markers here").contains("Your notes here"));
    }
}
