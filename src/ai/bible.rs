//! The on-disk story-bible format, shared by the AI trackers (characters #74,
//! timeline #75, setting #77). A bible file is YAML front matter, a delimited
//! **generated block** (rewritten each pass, change-detected by a `digest`), and
//! an author-owned **Notes block** carried over verbatim. This module is
//! content-agnostic: each tracker builds its own front matter + generated body
//! and calls [`render`].

use std::collections::hash_map::DefaultHasher;
use std::fmt::Write;
use std::hash::{Hash, Hasher};
use std::path::Path;

const GEN_START: &str = "<!-- generated:start -->";
const GEN_END: &str = "<!-- generated:end -->";
const NOTES_START: &str = "<!-- notes:start -->";
const NOTES_END: &str = "<!-- notes:end -->";
const NOTES_PLACEHOLDER: &str = "## Notes\n\n_Your notes here — preserved across regeneration._\n";

/// The prefix of the human-readable provenance line (#832) at the top of a
/// generated block — a blockquote so it renders as a callout and is easy to
/// recognize and strip. The line reads e.g. `> Generated from ch. 1–12 ·
/// AI-generated`; after a hand-edit a reader relabels the state as `edited by
/// you`, derived live from the `digest:` rather than stored (writing the new
/// state would itself count as an edit).
const PROVENANCE_PREFIX: &str = "> Generated from ";
const STATE_GENERATED: &str = "AI-generated";
const STATE_EDITED: &str = "edited by you";
const STATE_SEP: &str = " · ";

/// Assemble a bible file from caller-built `front` matter lines (each ending in
/// `\n`, no trailing `---`), the regenerated `generated` body, the author's
/// `notes`, and the generation date `today`. Adds the `generated`/`digest` front
/// matter and the block markers.
pub fn render(front: &str, generated: &str, notes: &str, today: &str) -> String {
    let digest = digest(generated);
    format!(
        "---\n# Generated by Quill — edit the Notes section; the rest is rewritten \
on the next pass.\n{front}generated: {today}\ndigest: {digest}\n---\n\n\
{GEN_START}\n{generated}{GEN_END}\n\n{NOTES_START}\n{notes}{NOTES_END}\n"
    )
}

/// The provenance line for a generated block whose source is `source` (a readable
/// chapter descriptor, e.g. `ch. 1–12`), labeled with the given `state`.
fn provenance_line(source: &str, state: &str) -> String {
    format!("{PROVENANCE_PREFIX}{source}{STATE_SEP}{state}")
}

/// Insert (or refresh) the human-readable provenance line at the top of a rendered
/// bible file's generated block (#832), naming the `source` chapters it was built
/// from, and rewrite the `digest:` so a freshly generated file still reads as
/// clean. The line becomes part of the generated block — rewritten on every pass,
/// so an incremental update refreshes the source — while the AI-generated / edited
/// state is left to a reader ([`provenance`]) to derive live from the digest. A
/// file without a generated block (foreign / import) is returned unchanged.
pub fn with_provenance(rendered: &str, source: &str) -> String {
    let Some(body) = between(rendered, GEN_START, GEN_END) else {
        return rendered.to_string();
    };
    let line = provenance_line(source, STATE_GENERATED);
    let block = format!("{line}\n\n{body}");
    let start = format!("{GEN_START}\n");
    let Some(pos) = rendered.find(&start) else {
        return rendered.to_string();
    };
    let head = &rendered[..pos + start.len()];
    let tail_at = rendered[pos..].find(GEN_END).map(|i| pos + i);
    let Some(tail_at) = tail_at else {
        return rendered.to_string();
    };
    let rebuilt = format!("{head}{block}{}", &rendered[tail_at..]);
    // The provenance line is inside the digested block, so re-stamp the digest over
    // the new block content — otherwise the freshly written file would read as
    // hand-edited on the very next check.
    restamp_digest(&rebuilt, &block)
}

/// Rewrite the `digest:` front-matter field of `file` to the digest of `block`
/// (the generated block's new content), so a file we just rewrote isn't misread as
/// hand-edited.
fn restamp_digest(file: &str, block: &str) -> String {
    let want = digest(block);
    let mut out = String::with_capacity(file.len());
    let mut done = false;
    for line in file.split_inclusive('\n') {
        if !done && line.trim_start().starts_with("digest:") {
            let indent = &line[..line.len() - line.trim_start().len()];
            let _ = writeln!(out, "{indent}digest: {want}");
            done = true;
        } else {
            out.push_str(line);
        }
    }
    out
}

/// The human-readable provenance of a generated bible file (#832), or `None` when
/// it carries no provenance line (a foreign / pre-#832 file). The source-chapter
/// text is read from the stored line; the state is derived live — `edited by you`
/// once the block no longer matches its `digest:`, else `AI-generated` — so the
/// author sees at a glance where an entry came from and whether they've touched it.
pub fn provenance(existing: &str) -> Option<String> {
    let block = between(existing, GEN_START, GEN_END).unwrap_or_default();
    let line = block.lines().next()?;
    let rest = line.strip_prefix(PROVENANCE_PREFIX)?;
    // Drop the stored state suffix; the live digest check is the source of truth.
    let source = rest.rsplit_once(STATE_SEP).map_or(rest, |(s, _)| s);
    let state = if is_hand_edited(existing) {
        STATE_EDITED
    } else {
        STATE_GENERATED
    };
    Some(provenance_line(source, state))
}

/// Append a `## {heading}` section with one `- ` bullet per item and a trailing
/// blank line, or nothing when `items` is empty — the shared shape for the
/// bullet-list sections in generated bible / notes blocks.
pub fn bullet_section(body: &mut String, heading: &str, items: &[String]) {
    if items.is_empty() {
        return;
    }
    let _ = writeln!(body, "## {heading}");
    for item in items {
        let _ = writeln!(body, "- {item}");
    }
    body.push('\n');
}

/// A bible file's human-readable content with the machine scaffolding removed —
/// the YAML front matter dropped and the generated/notes block-marker comments
/// stripped — for a clean, shareable export (#708). The generated body and the
/// author's Notes are kept (in that order), separated by a blank line and with
/// surrounding blank lines trimmed. A file with no markers (e.g. an imported or
/// foreign `.md`) falls back to its whole body sans front matter.
pub fn clean(raw: &str) -> String {
    let body = crate::frontmatter::split(raw).1;
    // Drop the provenance line (#832) — it's metadata about the entry, not part of
    // the shareable content the export assembles.
    let generated = between(body, GEN_START, GEN_END).map(|g| strip_provenance(&g));
    let notes = between(body, NOTES_START, NOTES_END);
    match (generated, notes) {
        (None, None) => body.trim().to_string(),
        (g, n) => [g, n]
            .into_iter()
            .flatten()
            .map(|s| s.trim().to_string())
            .filter(|s| !s.is_empty())
            .collect::<Vec<_>>()
            .join("\n\n"),
    }
}

/// The author's Notes block from an existing file, or the placeholder so a fresh
/// file still has the section.
pub fn extract_notes(existing: &str) -> String {
    between(existing, NOTES_START, NOTES_END).unwrap_or_else(|| NOTES_PLACEHOLDER.to_string())
}

/// Whether `existing`'s generated block has been hand-edited since it was written
/// (its content no longer matches the `digest:` recorded in the front matter).
pub fn is_hand_edited(existing: &str) -> bool {
    let Some(stored) = front_field(existing, "digest") else {
        return false; // no digest (older/foreign file) — treat as clean
    };
    let current = between(existing, GEN_START, GEN_END).unwrap_or_default();
    digest(&current) != stored
}

/// A filename-safe slug, e.g. "Mara Vance" → "mara-vance" (→ "unnamed" if empty).
pub fn slug(name: &str) -> String {
    let mut out = String::new();
    let mut prev_dash = false;
    for ch in name.chars() {
        if ch.is_alphanumeric() {
            out.extend(ch.to_lowercase());
            prev_dash = false;
        } else if !prev_dash && !out.is_empty() {
            out.push('-');
            prev_dash = true;
        }
    }
    let slug = out.trim_end_matches('-').to_string();
    if slug.is_empty() {
        "unnamed".to_string()
    } else {
        slug
    }
}

/// Minimal YAML scalar quoting: quote when the value could be misread (including
/// flow-context chars `[]{},` since aliases are written as `[a, b]`).
pub fn yaml(value: &str) -> String {
    let needs_quote = value.is_empty()
        || value.starts_with(|c: char| c.is_whitespace())
        || value.ends_with(|c: char| c.is_whitespace())
        || value.contains([':', '#', '"', '\'', '[', ']', '{', '}', ',']);
    if needs_quote {
        format!("\"{}\"", value.replace('\\', "\\\\").replace('"', "\\\""))
    } else {
        value.to_string()
    }
}

/// Stable change-detection hash of a block of text (not cryptographic). The one
/// source of the persisted-hash format, shared by the generated-block digest and
/// the incremental-scoping chapter digests (#90).
pub fn digest(generated: &str) -> String {
    let mut h = DefaultHasher::new();
    generated.hash(&mut h);
    format!("{:016x}", h.finish())
}

/// An existing single-file bible (`bible/<rel>`) as raw text — the cache for an
/// incremental revise (#90), empty when absent.
pub fn raw_file(root: &Path, rel: &str) -> String {
    std::fs::read_to_string(root.join("bible").join(rel)).unwrap_or_default()
}

/// The existing `.md` bible files under `bible/<dir>/` (e.g. the per-character
/// profiles), concatenated as the cache for an incremental revise (#90).
pub fn raw_dir(root: &Path, dir: &str) -> String {
    let mut out = String::new();
    let Ok(entries) = std::fs::read_dir(root.join("bible").join(dir)) else {
        return out;
    };
    let mut files: Vec<std::path::PathBuf> = entries.flatten().map(|e| e.path()).collect();
    files.sort();
    for path in files {
        if path.extension().and_then(|e| e.to_str()) == Some("md") {
            if let Ok(text) = std::fs::read_to_string(&path) {
                out.push_str(&text);
                out.push_str("\n\n");
            }
        }
    }
    out
}

/// A generated block with its provenance line (#832) and the blank line after it
/// removed, if present — leaving only the tracked content. The reader counterpart
/// to [`with_provenance`], used by [`clean`] so exports stay prose-only.
fn strip_provenance(block: &str) -> String {
    let Some(rest) = block.strip_prefix(PROVENANCE_PREFIX) else {
        return block.to_string();
    };
    // Drop the provenance line itself and the blank line separating it from the
    // content; a block that is *only* the line leaves nothing behind.
    rest.split_once('\n')
        .map_or_else(String::new, |(_, after)| {
            after.trim_start_matches('\n').to_string()
        })
}

/// The text strictly between `start` and `end` markers, if both are present.
fn between(text: &str, start: &str, end: &str) -> Option<String> {
    let s = text.find(start)? + start.len();
    let e = text[s..].find(end)? + s;
    Some(text[s..e].trim_start_matches('\n').to_string())
}

/// A scalar field value from the YAML front matter (first `key: value` line).
pub fn front_field(text: &str, key: &str) -> Option<String> {
    let body = text.strip_prefix("---\n")?;
    let end = body.find("\n---")?;
    body[..end].lines().find_map(|line| {
        let (k, v) = line.split_once(':')?;
        (k.trim() == key).then(|| v.trim().to_string())
    })
}

/// The `- item` bullets under the `## {heading}` section of a bible file, up to
/// the next `##` heading or block marker. The reader counterpart to the section
/// writing the trackers do (e.g. the setting "Gazetteer" list).
pub fn list_items(text: &str, heading: &str) -> Vec<String> {
    let mut items = Vec::new();
    let mut in_section = false;
    for line in text.lines() {
        if let Some(h) = line.strip_prefix("## ") {
            in_section = h.trim() == heading;
        } else if in_section {
            if line.starts_with("<!--") {
                break; // end of the generated block
            }
            if let Some(item) = line.strip_prefix("- ") {
                items.push(item.trim().to_string());
            }
        }
    }
    items
}

// --- The author's research notebook (#932) ----------------------------------

/// The author-maintained research / worldbuilding notebook file (#932), relative
/// to `bible/`: a bible-like journal of historical refs, magic-system sources,
/// and worldbuilding rules that the AI's trackers can *cite* but never write. The
/// author owns every word — the AI-write path (`stage_bible`) targets the tracker
/// files, never this one; [`scaffold_research`] only seeds an empty template.
pub const RESEARCH_FILE: &str = "research.md";

/// The seed template for a fresh research notebook (#932): an author-facing header
/// explaining the file and one `## ` heading to write under. It is deliberately
/// prose-free — Quill seeds structure, never worldbuilding content — so the
/// no-AI-write invariant holds even for the first write.
const RESEARCH_TEMPLATE: &str =
    "# Research notebook\n\n_Your research and worldbuilding journal — you write it, \
Quill's trackers only cite it. Give each note a `## ` heading so a bible entry can \
reference it by name._\n\n## Example note\n\n_Replace this with your own research._\n";

/// The path to the author's research notebook (#932): `bible/research.md` under the
/// project `root`.
pub fn research_path(root: &Path) -> std::path::PathBuf {
    root.join("bible").join(RESEARCH_FILE)
}

/// A readable citation to one of the author's research notes (#932), for a
/// generated bible / tracker entry to ground a claim against — e.g. `per research
/// note 'Feudal Timeline'`. The one source of the citation phrasing, so a tracker
/// bullet and a reader recognize the same shape. The AI only *emits* this
/// reference; it never writes the note it points at.
pub fn cite_research(note: &str) -> String {
    format!("per research note '{}'", note.trim())
}

/// The note titles the author has written in the research notebook (#932) — the
/// `## ` headings in `bible/research.md`, in file order — so a tracker can cite a
/// note that actually exists (and a reader can validate a citation). Empty when the
/// notebook is absent or the author has only the seed template. The template's
/// `## Example note` heading is skipped so a fresh, untouched notebook cites
/// nothing.
pub fn research_notes(root: &Path) -> Vec<String> {
    let Ok(text) = std::fs::read_to_string(research_path(root)) else {
        return Vec::new();
    };
    text.lines()
        .filter_map(|line| line.strip_prefix("## "))
        .map(|h| h.trim().to_string())
        .filter(|h| !h.is_empty() && h != "Example note")
        .collect()
}

/// Whether `text` carries a readable research citation (#932) — the shape
/// [`cite_research`] emits. The reader counterpart used to prove a tracker entry
/// grounds against a note.
pub fn has_research_citation(text: &str) -> bool {
    text.contains("per research note '")
}

/// Create the author's research notebook (#932) with the seed template *only when
/// it is absent*, so opening it never clobbers what the author has written.
/// Returns the path either way. This is the only write Quill makes to the
/// notebook, and it writes structure, not content — the author authors every
/// note. An I/O failure surfaces to the caller.
pub fn scaffold_research(root: &Path) -> std::io::Result<std::path::PathBuf> {
    let path = research_path(root);
    if !path.exists() {
        if let Some(parent) = path.parent() {
            std::fs::create_dir_all(parent)?;
        }
        std::fs::write(&path, RESEARCH_TEMPLATE)?;
    }
    Ok(path)
}

// --- Reading the project's bible (the typed counterpart to the writers) -----

/// The place/term gazetteer from `bible/setting.md` (empty when absent).
pub fn gazetteer(root: &Path) -> Vec<String> {
    let path = root.join("bible").join("setting.md");
    std::fs::read_to_string(path)
        .map(|t| list_items(&t, "Gazetteer"))
        .unwrap_or_default()
}

/// The character names from `bible/characters/*.md` front matter (empty when
/// absent), sorted for a deterministic order. De-duplication is the caller's job
/// (e.g. `known_entities` dedups the combined gazetteer + names).
pub fn character_names(root: &Path) -> Vec<String> {
    let dir = root.join("bible").join("characters");
    let mut names: Vec<String> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|entry| std::fs::read_to_string(entry.path()).ok())
        .filter_map(|text| front_field(&text, "name"))
        .collect();
    names.sort();
    names
}

/// One bible entry paired with the chapters it appears in — the shape the
/// co-occurrence read (#922) works over, read back from the rendered bible files
/// the trackers wrote. Character appearances come from the per-chapter Arc beats;
/// motif appearances from the tracker's "Appears in" line.
pub struct Appearances {
    pub name: String,
    pub chapters: Vec<String>,
}

/// Each character's per-chapter appearances read from `bible/characters/*.md`
/// (#922): the name from front matter, the chapters from the `## Arc` beats — each
/// a `- **<chapter>:** <state>` line the profile renderer wrote. Empty when the
/// character bible is absent. Sorted by name for a deterministic read.
pub fn character_appearances(root: &Path) -> Vec<Appearances> {
    let dir = root.join("bible").join("characters");
    let mut out: Vec<Appearances> = std::fs::read_dir(dir)
        .into_iter()
        .flatten()
        .flatten()
        .filter_map(|entry| std::fs::read_to_string(entry.path()).ok())
        .filter_map(|text| {
            let name = front_field(&text, "name")?;
            Some(Appearances {
                chapters: arc_chapters(&text),
                name,
            })
        })
        .collect();
    out.sort_by(|a, b| a.name.cmp(&b.name));
    out
}

/// The chapter titles named by the `## Arc` beats of a character bible file — the
/// bold label of each `- **<chapter>:** <state>` bullet, up to the next `##`
/// heading or block marker.
fn arc_chapters(text: &str) -> Vec<String> {
    let mut chapters = Vec::new();
    let mut in_arc = false;
    for line in text.lines() {
        if let Some(h) = line.strip_prefix("## ") {
            in_arc = h.trim() == "Arc";
        } else if in_arc {
            if line.starts_with("<!--") {
                break; // end of the generated block
            }
            if let Some(rest) = line.strip_prefix("- **") {
                if let Some(chapter) = rest.split_once(":**").map(|(c, _)| c.trim()) {
                    chapters.push(chapter.to_string());
                }
            }
        }
    }
    chapters
}

/// Each motif's appearances read from `bible/theme.md` (#922): the motif name from
/// its `### <name> — <status>` heading, the chapters from the `- **Appears in:**
/// <a, b, c>` line the theme renderer wrote. Empty when the theme bible is absent.
pub fn motif_appearances(root: &Path) -> Vec<Appearances> {
    let path = root.join("bible").join("theme.md");
    let Ok(text) = std::fs::read_to_string(path) else {
        return Vec::new();
    };
    let mut out = Vec::new();
    let mut current: Option<Appearances> = None;
    for line in text.lines() {
        if let Some(head) = line.strip_prefix("### ") {
            if let Some(entry) = current.take() {
                out.push(entry);
            }
            // The heading is `<name> — <status>`; keep only the name.
            let name = head.split(" — ").next().unwrap_or(head).trim().to_string();
            current = Some(Appearances {
                name,
                chapters: Vec::new(),
            });
        } else if let Some(entry) = current.as_mut() {
            if let Some(list) = line.strip_prefix("- **Appears in:** ") {
                entry.chapters = list.split(", ").map(|c| c.trim().to_string()).collect();
            }
        }
    }
    if let Some(entry) = current.take() {
        out.push(entry);
    }
    out
}

#[cfg(test)]
